<?php
declare(strict_types=1);
namespace VV\WPPorter;
defined('VV_ROOT') || exit;

final class Generator {
    public static function build(Archive $source,array $analysis,string $id,string $name): array {
        if(!preg_match('/^[a-z][a-z0-9-]{1,50}$/D',$id)) throw new PortError('Identifiant natif invalide (2–51 caractères).','Invalid native ID (2–51 lowercase letters/digits/hyphens).');
        $name=Archive::clean($name,120);if($name==='') throw new PortError('Nom natif requis.','Native name is required.');
        $r=$analysis['report'];$p=$analysis['program'];$auto=$r['status']==='converted';$type=$r['source']['type'];
        if($auto && $type==='theme') {
            $assetBytes=0;$tooLong=false;
            foreach($p['assets'] as $path) {$assetBytes+=strlen($source->files[$path]);if(strlen($id.'/'.$path)>220) $tooLong=true;}
            if(count($p['assets'])>365 || $assetBytes>16777216 || $tooLong) {
                Analyzer::issue($r,'native_limits','Les ressources dépassent les limites du paquet natif ; projet à réduire.','Assets exceed native package limits; reduce the project.');
                $r['status']='manual';$r['summary']['blockers']++;$auto=false;
            }
        }
        $r['target']['id']=$id;$r['target']['name']=$name;
        $files=[];
        $m=['api'=>1,'id'=>$id,'type'=>$type,'name'=>($auto?'':'[PORTAGE / DRAFT] ').$name,'version'=>'0.1.0','description'=>$auto?'Portage limité généré par WordPress Porter ; vérifier le rapport.':'Projet à finaliser : fonctionnalités WordPress non migrées.','description_en'=>$auto?'Limited native port generated by WordPress Porter; review its report.':'Porting draft: original WordPress behavior is not migrated.','porting'=>['status'=>$r['status'],'source_sha256'=>$source->sha256,'source_name'=>$r['source']['name'],'source_version'=>$r['source']['version']]];
        if($type==='plugin') $files['plugin.php']=$auto?self::plugin($p):self::draftPlugin();
        else {
            if($auto) {
                $class='T'.substr(hash('sha256',$id),0,16);
                $runtime=file_get_contents(dirname(__DIR__).'/runtime/Theme.php');
                $files['PortTheme.php']=str_replace('namespace VV\\WPPorterRuntime;','namespace VV\\WPPorterGenerated\\'.$class.';',$runtime);
                $files['index.php']="<?php\ndeclare(strict_types=1);\ndefined('VV_ROOT') || exit;\nrequire_once __DIR__.'/PortTheme.php';\n\$context=['current'=>\$current ?? null,'items'=>\$items ?? [],'query'=>\$query ?? '', 'notFound'=>\$notFound ?? false];\n(new \\VV\\WPPorterGenerated\\$class\\Theme(\$app,\$context,__DIR__,".var_export($id,true)."))->render();\n";
                $files['templates.json']=self::json($p);
                foreach($p['assets'] as $asset) $files[$asset]=$source->files[$asset];
            } else {
                $files['index.php']=self::draftTheme();
                $files['style.css']='body{margin:0;background:#10151b;color:#eee;font:17px/1.7 system-ui}main{max-width:900px;margin:40px auto;padding:24px}a{color:#dfbe81}article{padding:25px 0;border-bottom:1px solid #454b52}.porting-note{padding:16px;border:1px solid #dfbe81}';
            }
        }
        // Original code stays inert as .txt; the ZIP never includes original executable PHP.
        $reference=[];$referenceBytes=0;
        $referenceCount=max(0,min(180,390-count($files)));
        $referenceMax=max(0,min(8388608,20971520-array_sum(array_map('strlen',$files))-2097152));
        foreach($source->files as $path=>$bytes) {
            if(!preg_match('/\.(php|inc|phtml|html|json|css|js|md|txt)$/i',$path) || count($reference)>=$referenceCount || $referenceBytes+strlen($bytes)>$referenceMax) continue;
            if(preg_match('~(?:^|/)(?:vendor|node_modules)/~',$path)) continue;
            $ref=sprintf('porting/source/%03d-',count($reference)+1).substr(preg_replace('/[^a-zA-Z0-9_.-]/','_',basename($path)),0,72).'.txt';
            $files[$ref]=$bytes;$reference[]=['original'=>$path,'reference'=>$ref];$referenceBytes+=strlen($bytes);
        }
        $r['references']=['included'=>$reference,'complete'=>count($reference)===count($source->files),'note_fr'=>'Références plafonnées ; conservez votre ZIP source complet.','note_en'=>'References are capped; keep the complete original ZIP.'];
        $r['files']=array_map(fn($path)=>['path'=>$path,'bytes'=>strlen($source->files[$path]),'sha256'=>hash('sha256',$source->files[$path])],array_keys($source->files));
        $files['cms.json']=self::json($m);
        $files['porting/report.json']=self::json($r);
        $files['porting/REPORT.md']=self::markdown($r);
        $files['README.md']=self::readme($r);
        $license=[];
        foreach($source->files as $path=>$bytes) if(preg_match('~^(?:license|licence|copying)(?:\.(?:txt|md))?$~i',$path)) $license[]=$path."\n\n".$bytes;
        $files['SOURCE-NOTICE.txt']='Original source / Source originale: '.$r['source']['name'].' '.$r['source']['version']."\nAuthor / Auteur: ".$r['source']['author']."\nLicense header / En-tête licence: ".$r['source']['license']."\nThe original rights are not reassigned. Review distribution terms.\nLes droits d’origine ne sont pas réattribués. Vérifiez les conditions de diffusion.\n\n".implode("\n\n",$license);
        if(count($files)>400 || array_sum(array_map('strlen',$files))>20971520) throw new PortError('Le projet dépasse les limites natives (400 fichiers / 20 Mio). Réduisez le ZIP source.','Generated project exceeds native limits (400 files / 20 MiB). Reduce the source ZIP.',413);
        $temp=tempnam(sys_get_temp_dir(),'vv-port-');if($temp===false) throw new PortError('Fichier temporaire indisponible.','Cannot create temporary file.',503);chmod($temp,0600);
        $z=new \ZipArchive();
        try {
            if($z->open($temp,\ZipArchive::OVERWRITE)!==true) throw new PortError('ZIP de sortie indisponible.','Cannot create output ZIP.',503);
            foreach($files as $path=>$bytes) {
                if(strlen($id.'/'.$path)>220 || strlen($bytes)>8388608) throw new PortError('Nom ou taille de fichier incompatible avec le CMS. Réduisez le paquet source.','A generated path or file exceeds CMS limits. Reduce the source package.',413);
                if(!$z->addFromString($id.'/'.$path,$bytes)) throw new PortError('Écriture ZIP interrompue.','ZIP write failed.',503);
            }
            if(!$z->close()) throw new PortError('Finalisation ZIP impossible.','Cannot finish ZIP.',503);
            $bytes=file_get_contents($temp);
            if(!is_string($bytes) || strlen($bytes)>12582912) throw new PortError('ZIP généré trop volumineux.','Generated ZIP is too large.',413);
            return ['report'=>$r,'bytes'=>$bytes,'filename'=>$id.($auto?'-native':'-porting-draft').'.zip'];
        } finally {if(is_file($temp)) unlink($temp);}
    }
    public static function json(array $data): string {return json_encode($data,JSON_PRETTY_PRINT|JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES|JSON_THROW_ON_ERROR)."\n";}
    public static function markdown(array $r): string {
        $safe=fn($s)=>str_replace(['`',"\r","\n"],['', ' ',' '],(string)$s);
        $s="# Porting report / Rapport de portage\n\n".$safe($r['source']['name']).' '.$safe($r['source']['version'])."\n\nStatus / Statut: **".$r['status']."**\n\n";
        $s.=$r['status']==='converted'?"Generated for the supported subset; review and test locally.\nPortage du sous-ensemble pris en charge ; relire et tester localement.\n\n":"This is a draft. Original WordPress behavior is not implemented.\nCeci est un projet à finaliser. Le comportement WordPress d’origine n’est pas implémenté.\n\n";
        foreach($r['issues'] as $i) $s.='- ['.$i['severity'].'] '.$safe($i['file']).($i['line']?':'.$i['line']:'').' — '.$safe($i['fr']).' / '.$safe($i['en'])."\n";
        $s.="\n## API mapping / Correspondances\n\n";
        foreach($r['apis'] as $api) $s.='- `'.$safe($api['name']).'` ('.$api['count'].') → '.$safe($api['native'] ?: 'Manual design / Conception manuelle').' — '.$safe($api['note'])."\n";
        return $s."\nThe source was not executed, remotely transmitted, installed or activated.\nLa source n’a pas été exécutée, transmise, installée ou activée.\n";
    }
    private static function plugin(array $p): string {
        $out="<?php\ndeclare(strict_types=1);\ndefined('VV_ROOT') || exit;\n// Generated native registrations; original PHP is not included.\n";
        foreach($p['features'] as $f) {
            $html=var_export($f['html'],true);
            if($f['kind']==='shortcode') $out.='vv_shortcode('.var_export($f['tag'],true).', static function(){ return \\VV\\Content::html('.$html."); });\n";
            elseif($f['kind']==='footer') $out.='vv_action(\'footer\', static function($app){ echo \\VV\\Content::html('.$html.'); }, '.(int)$f['priority'].");\n";
            else {
                $parts=[];foreach($f['parts'] as $part) $parts[]=isset($part['slot'])?'$html':var_export($part['text'],true);
                $out.='vv_action(\'content_html\', static function($html,$content){ return \\VV\\Content::html('.implode('.',$parts).'); }, '.(int)$f['priority'].");\n";
            }
        }
        return $out;
    }
    private static function draftPlugin(): string {
        return <<<'PHP'
<?php
declare(strict_types=1);
defined('VV_ROOT') || exit;
// Draft only: implement the plan in porting/REPORT.md before using original features.
vv_action('admin_dashboard', static function($app) {
    echo '<section class="panel"><h2>'.e(t('Projet de portage à finaliser','Porting draft to finish')).'</h2><p>'.e(t('Cette extension ne reprend pas les fonctions WordPress. Consultez porting/REPORT.md.','This plugin does not implement the original WordPress behavior. Read porting/REPORT.md.')).'</p></section>';
});
PHP;
    }
    private static function draftTheme(): string {
        return <<<'PHP'
<?php
declare(strict_types=1);
defined('VV_ROOT') || exit;
$rows=$current?[$current]:$items;
?><!doctype html><html lang="<?=e(lang())?>"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title><?=e($app->state['settings']['title'])?></title><link rel="stylesheet" href="<?=e(url('content/themes/'.$app->theme().'/style.css'))?>"><?php vv_do('head',$app,$current);?></head><body><main><p class="porting-note"><?=e(t('Projet de portage : le thème WordPress d’origine reste à adapter.','Porting draft: the original WordPress theme still needs adaptation.'))?></p><h1><?=e($app->state['settings']['title'])?></h1><?php foreach($rows as $row):?><article><h2><a href="<?=e(\VV\Content::url($row))?>"><?=e(\VV\Content::field($row,'title'))?></a></h2><?=$app->body($row)?></article><?php endforeach;?><?php if($notFound):?><h2>404</h2><?php endif;?></main><?php vv_do('footer',$app);?></body></html>
PHP;
    }
    private static function readme(array $r): string {
        return "# ".$r['target']['name']."\n\nStatus / Statut: **".$r['status']."**.\n\n".
            "Read porting/REPORT.md and report.json before installing. Install through the CMS native ZIP installer, then review/test on an isolated copy before activation. No activation or replacement was performed.\n\n".
            "Lisez porting/REPORT.md et report.json. Installez avec l’installateur ZIP natif, puis relisez/testez sur une copie isolée avant activation. Aucun remplacement ni activation automatique.\n\n".
            "A draft is not a working conversion of the original. Original code is inert in porting/source/*.txt and may be incomplete due to size limits. Keep the original source ZIP. No site data is migrated.\n\n".
            "Un projet à finaliser n’est pas une conversion fonctionnelle de l’original. Le code source reste inerte dans porting/source/*.txt ; les références peuvent être partielles. Conservez le ZIP source. Aucune donnée du site n’est migrée.\n";
    }
}
