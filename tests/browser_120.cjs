'use strict';
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const base=process.env.VV_TEST_BASE,work=process.env.VV_BROWSER_WORK;
 if(!base||!work)throw Error('Run through tests/browser_120.py');
 const launch={headless:true,args:['--no-sandbox']};
 if(process.env.VV_BROWSER_EXECUTABLE)launch.executablePath=process.env.VV_BROWSER_EXECUTABLE;
 const browser=await chromium.launch(launch),checks=[],errors=[];
 const owner=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await owner.newPage();page.on('pageerror',e=>errors.push(e.message));
 const ck=(name,ok)=>{if(!ok)throw Error(name);checks.push(name);};
 const save=async()=>{await Promise.all([page.waitForURL(/admin\.php\?view=editor.*id=/),page.locator('#content-editor button[type=submit]').click()]);await page.waitForLoadState('networkidle');};
 await page.goto(base+'/login.php');await page.locator('input[name=password]').fill('Browser_validation_120!');
 await Promise.all([page.waitForURL('**/admin.php*'),page.getByRole('button',{name:'Ouvrir mon espace'}).click()]);
 ck('owner signs in with browser',await page.locator('h1').innerText()==='Vue d’ensemble.');
 await page.goto(base+'/admin.php?view=media');
 await page.locator('input[name=file]').setInputFiles(path.join(work,'report.docx'));
 await Promise.all([page.waitForURL('**/admin.php*'),page.getByRole('button',{name:'Importer le fichier',exact:true}).click()]);
 await page.waitForLoadState('networkidle');
 ck('browser upload accepts validated DOCX with DOCX label',await page.locator('.media-card').filter({hasText:'report.docx'}).locator('.media-thumb strong').innerText()==='DOCX');
 await page.locator('input[name=file]').setInputFiles(path.join(work,'Ressources & tarif.csv'));
 await Promise.all([page.waitForURL('**/admin.php*'),page.getByRole('button',{name:'Importer le fichier',exact:true}).click()]);
 await page.waitForLoadState('networkidle');
 await page.goto(base+'/admin.php?view=editor');
 await page.locator('input[name=title_fr]').fill('Documents et commentaires');
 await page.locator('#body-fr').fill('<p>Un document pour les visiteurs.</p>');
 await page.locator('select[name=insert_document]').selectOption({label:'Ressources & tarif.csv · CSV'});
 await page.locator('#insert-document').click();
 const french=await page.locator('#body-fr').inputValue();
 ck('document picker inserts escaped link in French',french.includes('Ressources &amp; tarif.csv')&&french.includes('download=1')&&!french.includes('<img'));
 await page.locator('.language-tab[data-language=en]').click();
 await page.locator('input[name=title_en]').fill('Documents and comments');
 await page.locator('select[name=insert_document]').selectOption({label:'report.docx · DOCX'});
 await page.locator('#insert-document').click();
 ck('English insertion leaves French text unchanged',(await page.locator('#body-en').inputValue()).includes('report.docx')&&(await page.locator('#body-fr').inputValue())===french);
 await page.locator('select[name=status]').selectOption('published');
 await page.locator('input[name=publish_at]').fill('2000-01-01T12:00');
 await save();
 ck('browser editor saves attachment links',await page.locator('input[name=title_fr]').inputValue()==='Documents et commentaires');
 const postUrl=await page.locator('a[target=_blank]').filter({hasText:'Voir sur le site'}).getAttribute('href');
 const id=new URL(postUrl,base).searchParams.get('preview');
 const publicUrl=base+'/index.php?p=documents-et-commentaires';
 const visitors=await browser.newContext({viewport:{width:1440,height:1000}});
 const visitor=await visitors.newPage();visitor.on('pageerror',e=>errors.push(e.message));
 await visitor.goto(publicUrl);
 const downloadPromise=visitor.waitForEvent('download');
 await visitor.locator('.prose a').filter({hasText:'Ressources & tarif.csv'}).click();
 const download=await downloadPromise;
 ck('document link downloads under its original display filename',download.suggestedFilename()==='Ressources & tarif.csv');
 await visitor.locator('#comment-name').fill('Browser visitor');
 await visitor.locator('#comment-body').fill('Un commentaire envoyé depuis le navigateur.');
 await visitor.locator('input[name=consent]').check();
 await Promise.all([visitor.waitForURL('**/*comment=received*'),visitor.getByRole('button',{name:'Envoyer pour validation'}).click()]);
 ck('guest browser submission waits for moderation',await visitor.getByRole('status').filter({hasText:'Votre message sera visible'}).count()===1&&await visitor.locator('.vv-comment').count()===0);
 await page.goto(base+'/admin.php?view=plugin-comments');
 const card=page.locator('article.panel').filter({hasText:'Un commentaire envoyé depuis le navigateur.'});
 await Promise.all([page.waitForURL('**/admin.php*'),card.getByRole('button',{name:'Approuver',exact:true}).click()]);
 await visitor.reload();
 ck('owner browser moderation publishes comment',await visitor.locator('.vv-comment').filter({hasText:'Un commentaire envoyé depuis le navigateur.'}).count()===1);
 fs.mkdirSync(path.join(work,'qa'),{recursive:true});
 await visitor.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
 await visitor.screenshot({path:path.join(work,'qa/comments-desktop.png'),fullPage:true});
 const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
 const plain=await nojs.newPage();await plain.goto(publicUrl);
 ck('public comment form works without JavaScript',await plain.locator('#comment-body').isVisible());
 await nojs.close();
 await page.goto(base+'/admin.php?view=editor&id='+id);
 await page.locator('input[name=comments_open]').uncheck();await save();await visitor.reload();
 ck('closing comments preserves approved messages',await visitor.locator('#comment-body').count()===0&&await visitor.locator('.vv-comment').count()===1);
 await page.setViewportSize({width:390,height:844});
 for(const view of ['media','editor','plugin-comments','tools','plugins']){
  await page.goto(base+'/admin.php?view='+view);await page.waitForLoadState('networkidle');
  await page.waitForFunction(()=>{const el=document.querySelector('#sidebar');return !el||el.getBoundingClientRect().right<=1;});
  ck('mobile layout '+view,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  if(view==='plugin-comments')await page.screenshot({path:path.join(work,'qa/comments-admin-mobile.png'),fullPage:true});
 }
 await visitor.setViewportSize({width:390,height:844});await visitor.goto(publicUrl+'&lang=en');
 ck('public mobile English comments and attachment',await visitor.locator('#comments-title').innerText()==='Comments (1)'&&await visitor.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await visitor.screenshot({path:path.join(work,'qa/comments-mobile.png'),fullPage:true});
 await page.goto(base+'/admin.php?view=plugin-comments&lang=en');
 ck('moderation UI switches to English',await page.locator('h1').innerText()==='Comments.'&&(await page.locator('main').innerText()).includes('Publish after approval'));
 ck('no JavaScript runtime errors',errors.length===0);
 const report={checks:checks.length,passed:checks,errors,browser:await browser.version()};
 fs.writeFileSync(path.join(work,'browser-report.json'),JSON.stringify(report,null,2)+'\n');
 await browser.close();console.log(JSON.stringify(report));
})().catch(e=>{console.error(e);process.exit(1)});
